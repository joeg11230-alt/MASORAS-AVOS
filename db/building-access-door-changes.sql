-- Building Access: Door Schedule Changes tracker
-- Apply to the MASORAS AVOS Supabase project.

create table public.building_access_door_changes (
  id bigint generated by default as identity primary key,
  door_name text not null check (char_length(trim(door_name)) between 1 and 120),
  normal_schedule text,
  temporary_mode text not null check (temporary_mode in ('unlocked','locked','special_schedule','other')),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  occasion text,
  notes text,
  status text not null default 'planned' check (status in ('planned','changed','restored')),
  changed_at timestamptz,
  restored_at timestamptz,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint building_access_door_changes_time_check check (ends_at > starts_at)
);

create index building_access_door_changes_status_ends_idx
  on public.building_access_door_changes (status, ends_at);
create index building_access_door_changes_created_by_idx
  on public.building_access_door_changes (created_by);

alter table public.building_access_door_changes enable row level security;

revoke all on table public.building_access_door_changes from public, anon, authenticated;
grant select, insert, update, delete on table public.building_access_door_changes to authenticated;
grant select, insert, update, delete on table public.building_access_door_changes to service_role;
revoke all on sequence public.building_access_door_changes_id_seq from public, anon;
grant usage, select on sequence public.building_access_door_changes_id_seq to authenticated, service_role;

create policy "building access assigned users can read"
on public.building_access_door_changes for select
to authenticated
using ((select public.has_app_section('building_access')));

create policy "building access editors can insert"
on public.building_access_door_changes for insert
to authenticated
with check (
  (select public.can_edit_app_section('building_access'))
  and created_by = (select auth.uid())
);

create policy "building access editors can update"
on public.building_access_door_changes for update
to authenticated
using ((select public.can_edit_app_section('building_access')))
with check ((select public.can_edit_app_section('building_access')));

create policy "building access editors can delete"
on public.building_access_door_changes for delete
to authenticated
using ((select public.can_edit_app_section('building_access')));
